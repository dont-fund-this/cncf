pub fn draw(
    back: &mut [u16],
    width: usize,
    height: usize,
    x: usize,
    y: usize,
    ch: char,
    color: u16,
) {
    if matches!(ch, '│' | '┼') {
        for py in y..y + 20 {
            put(back, width, height, x + 3, py, color);
        }
    }
    if matches!(ch, '─' | '┼') {
        for px in x..x + 8 {
            put(back, width, height, px, y + 9, color);
        }
    }
    if !matches!(ch, ' ' | '│' | '─' | '┼') {
        for (dy, row) in glyph(ch).iter().enumerate() {
            for dx in 0..8 {
                if row & (0x80 >> dx) != 0 {
                    put(back, width, height, x + dx, y + 6 + dy, color);
                }
            }
        }
    }
}

fn put(back: &mut [u16], w: usize, h: usize, x: usize, y: usize, color: u16) {
    if x < w && y < h {
        back[y * w + x] = color;
    }
}

fn glyph(ch: char) -> [u8; 8] {
    match ch {
        'a' => [0, 0, 0x3c, 6, 0x3e, 0x66, 0x66, 0x3d],
        'b' => [0x60, 0x60, 0x7c, 0x66, 0x66, 0x66, 0x66, 0x7c],
        'i' => [0x18, 0x18, 0, 0x1c, 0x18, 0x18, 0x18, 0x3c],
        'n' => [0, 0, 0x5c, 0x66, 0x66, 0x66, 0x66, 0x66],
        'o' => [0, 0, 0x3c, 0x66, 0x66, 0x66, 0x66, 0x3c],
        'p' => [0, 0, 0x7c, 0x66, 0x66, 0x7c, 0x60, 0xf0],
        'r' => [0, 0, 0x5c, 0x66, 0x60, 0x60, 0x60, 0xf0],
        't' => [0x10, 0x10, 0x7c, 0x10, 0x10, 0x10, 0x16, 0x0c],
        '-' => [0, 0, 0, 0x3e, 0, 0, 0, 0],
        'வ' => [0x3e, 0x66, 0x66, 0x3e, 6, 6, 0x66, 0x3c],
        'ண' => [0x6c, 0x92, 0x92, 0xfe, 0x92, 0x92, 0x92, 0x92],
        'க' => [0x7e, 0x12, 0x12, 0x7e, 0x52, 0x52, 0x52, 0x7e],
        'ம' => [0x7e, 0x40, 0x40, 0x7c, 0x42, 0x42, 0x42, 0x7c],
        '்' => [0x18, 0x18, 0, 0, 0, 0, 0, 0],
        _ => [0xff, 0x81, 0x81, 0x81, 0x81, 0x81, 0x81, 0xff],
    }
}
